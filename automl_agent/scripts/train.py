def classify_exception(exc: BaseException) -> str:
    """Map an exception to a coarse ``error_type`` the Critic can reason about."""
    if isinstance(exc, MemoryError):
        return "oom"
    text = f"{type(exc).__name__}: {exc}".lower()
    if any(token in text for token in ("out of memory", "cuda", "cannot allocate", "alloc failed")):
        return "oom"
    if isinstance(exc, (FileNotFoundError, KeyError)) or "not found" in text:
        return "data_issue"
    if isinstance(exc, ValueError) and "unsupported model" in text:
        return "unsupported_model"
    if isinstance(exc, ValueError):
        return "data_issue"
    return "exception"


# Where the non-finite numbers were, when there were any. Private: not in
# ``privacy.PUBLIC_RESULT_FIELDS``, because a reasoning prompt already reads the only thing it
# needs from this — the metric is *absent* from ``metrics``, which the capability list defines
# as "not measured". The list exists for the human reading result.json and the log beside it.
NONFINITE_KEY = "nonfinite_dropped"


def drop_nonfinite(value: Any, path: str = "") -> tuple[Any, list[str]]:
    """``value`` with every non-finite number removed, and the paths of what was removed.

    The last guard before ``result.json`` is written, covering the *shape* rather than one producer —
    ``score_split`` already refuses a NaN metric, but one arriving through any other key would reach
    the file, and ``json.dumps`` writes it as bare ``NaN``.

    **Bare ``NaN`` is not JSON, and Python's own ``json.loads`` accepts it** — which is why it went
    unnoticed. Every comparison against the value is then False, so a goal check reads "did not reach
    the bar" while a report prints it as a measurement. Anything reading the file from outside Python
    simply fails.

    **Dropped, not replaced with ``null``**: absent means "not measured", which is what the metrics
    dict already means elsewhere. ``null`` would add a third state every reader has to learn.
    """
    if isinstance(value, dict):
        kept: dict[str, Any] = {}
        dropped: list[str] = []
        for key, item in value.items():
            here = f"{path}.{key}" if path else str(key)
            clean, gone = drop_nonfinite(item, here)
            dropped += gone
            if gone and clean is None and not isinstance(item, (dict, list)):
                continue
            kept[str(key)] = clean
        return kept, dropped
    if isinstance(value, list):
        kept_list: list[Any] = []
        dropped = []
        for index, item in enumerate(value):
            clean, gone = drop_nonfinite(item, f"{path}[{index}]")
            dropped += gone
            # Position matters in a list — an interval is ``[low, high]`` — so a removed
            # element becomes ``null`` instead of shortening the list around it.
            kept_list.append(clean)
        return kept_list, dropped
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return value, []
    if math.isfinite(value):
        return value, []
    return None, [path or "<root>"]


def write_result(
    out_path: Path,
    *,
    status: str,
    metrics: dict[str, Any],
    train_time_sec: float,
    error_type: str | None,
    log_tail: str,
    applied_hyperparams: dict[str, Any] | None = None,
    dropped_hyperparams: list[str] | None = None,
    applied_preprocessing: dict[str, Any] | None = None,
    applied_pipeline: list[str] | None = None,
    model_path: str | None = None,
    schema_path: str | None = None,
    paired: dict[str, Any] | None = None,
    internal_validation: dict[str, Any] | None = None,
    split: str = "val",
) -> None:
    payload = {
        "metrics": metrics,
        # Which rows these numbers are about. Always present, because a consumer that
        # cannot tell a validation score from a test score would compare the two as if
        # they meant the same thing.
        "split": split,
        # What the estimator was actually configured with, and what was thrown away on
        # the way. Always present, even on failure (nothing was applied then), so the
        # orchestrator never has to guess whether an absent key means "none" or "old
        # result file".
        "applied_hyperparams": dict(applied_hyperparams or {}),
        "dropped_hyperparams": list(dropped_hyperparams or []),
        # The imputation and scaling the pipeline was built with, which is not always what
        # the config asked for (see :func:`describe_preprocessing`). Empty on failure, when
        # there is no pipeline to describe.
        "applied_preprocessing": dict(applied_preprocessing or {}),
        "train_time_sec": round(float(train_time_sec), 3),
        "status": status,
        "error_type": error_type,
        "log_tail": log_tail,
        # The environment these numbers were produced in, on every result including the failed
        # ones — the cheapest field in the file and the one that decides whether two of them
        # are comparable at all (:mod:`automl_agent.threads`). Deliberately not in
        # ``privacy.PUBLIC_RESULT_FIELDS``: it is free-form text out of the environment, it has
        # no diagnostic use in a prompt, and the one bit a consumer needs from it — did it
        # change between the two attempts being compared — is carried as a boolean inside the
        # paired block.
        "threads": thread_state(),
    }
    if applied_pipeline:
        # One rendered line per step that really ran, in the order it ran. Omitted rather than
        # written empty, like ``internal_validation``: absent means the attempt used the flag
        # path, which is a different thing from a spec whose every step was dropped — that one
        # arrives as a list holding only the safety nets.
        #
        # Strings and not the spec echoed back, because the two have different jobs. The spec is
        # a request and already on disk in ``train_config.json``; this is the record, and the
        # thing a reader needs from it is *what ran in what order over which columns*, which is
        # one line each. It also means the field is a flat list of scalars, so
        # ``privacy._public_params`` carries it with no new filter.
        payload["applied_pipeline"] = list(applied_pipeline)
    if paired:
        # A block of scalars about a *comparison*, not about this model on these rows —
        # which is why it is not folded into ``metrics``. Kept even when it says "skipped",
        # so a reader can tell "not compared, and here is why" from "compared, found nothing".
        payload[PAIRED_KEY] = paired
    if internal_validation:
        # Omitted rather than written empty, unlike ``applied_hyperparams``: absent means
        # "the estimator held no rows back", which is the common case and needs no field.
        # An empty block would read as "held back, amount unknown".
        payload["internal_validation"] = internal_validation
    if model_path:
        # Local only. Not in ``privacy.PUBLIC_RESULT_FIELDS``, so it never enters a state
        # channel a prompt is rendered from — a fitted model is data-equivalent.
        payload["model_path"] = model_path
    if schema_path:
        # Same terms as ``model_path``, and for the same reason: the levels it lists are cell
        # values. Recorded so a reader of result.json can tell "fitted, and applicable to new
        # rows" from "fitted, and only scoreable on the file it was fitted from".
        payload["schema_path"] = schema_path
    payload, nonfinite = drop_nonfinite(payload)
    if nonfinite:
        payload[NONFINITE_KEY] = nonfinite
        # Into the log tail as well, because that is the field a human reads first and the one
        # the Critic sees on a failed iteration. Appended rather than replacing anything: the
        # exception line, if there is one, is still the more important half.
        payload["log_tail"] = (
            str(payload.get("log_tail") or "")
            + f"\nnon-finite values dropped from result.json: {', '.join(nonfinite)}"
        ).strip()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        # ``allow_nan=False`` is the assertion that the walk above did its job. It is a guard
        # rather than the mechanism: reaching it means a non-finite number arrived in a type
        # the walk does not recognise as a number, which is a bug here and not a bad score.
        text = json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=False)
    except ValueError as exc:
        # A valid file with fewer numbers in it beats an unreadable file: the orchestrator
        # treats a missing result.json as a crashed iteration, which would report this as
        # something the training run did rather than as something this function failed at.
        text = json.dumps(
            {
                "metrics": {},
                "split": split,
                "applied_hyperparams": {},
                "dropped_hyperparams": list(dropped_hyperparams or []),
                "applied_preprocessing": {},
                "train_time_sec": round(float(train_time_sec), 3),
                "status": status,
                "error_type": error_type,
                "log_tail": f"{log_tail}\nresult.json could not be serialised strictly: {exc}",
                "threads": thread_state(),
                NONFINITE_KEY: nonfinite or ["<unknown>"],
            },
            indent=2,
            ensure_ascii=False,
            allow_nan=False,
        )
    out_path.write_text(text, encoding="utf-8")


def apply_simulation(cfg: dict[str, Any], log: LogBuffer) -> None:
    """Deterministic failure injection, used by tests and the OOM/timeout drills."""
    sim = dict(cfg.get("simulate") or {})
    sleep_sec = float(sim.get("sleep_sec", 0) or 0)
    if sleep_sec > 0:
        log.write(f"simulate.sleep_sec={sleep_sec}: sleeping to trigger the orchestrator timeout")
        time.sleep(sleep_sec)
    failure = str(sim.get("fail") or "").lower()
    if failure == "crash":
        # Hard exit without writing result.json: emulates a segfault / CUDA hard
        # failure. Proves the orchestrator survives a dying subprocess.
        log.write("simulate.fail=crash: exiting hard without a result file")
        sys.stderr.write("simulated hard crash in training subprocess\n")
        sys.stderr.flush()
        os._exit(3)
    if failure == "oom":
        raise MemoryError("simulated out of memory during training")


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Fixed AutoML training script.")
    parser.add_argument("--config", required=True, help="path to the training config JSON")
    parser.add_argument("--out", required=True, help="path to write result.json")
    parser.add_argument(
        "--score-model",
        default=None,
        help=(
            "score the held-back test split with this saved model instead of fitting. "
            "Run once, after the loop, by nodes/holdout.py"
        ),
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    out_path = Path(args.out)
    log = LogBuffer()
    started = time.perf_counter()

    try:
        cfg: dict[str, Any] = json.loads(Path(args.config).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        write_result(
            out_path,
            status="error",
            metrics={},
            train_time_sec=time.perf_counter() - started,
            error_type="config_error",
            log_tail=f"failed to read config {args.config}: {exc}",
        )
        return 0

    if args.score_model:
        return _score_only(cfg, Path(args.score_model), out_path, log, started)

    try:
        apply_simulation(cfg, log)
        run = run_training(
            cfg,
            log,
            model_out=out_path.parent / MODEL_FILENAME,
            predictions_out=out_path.parent / PREDICTIONS_FILENAME,
            schema_out=out_path.parent / SCHEMA_FILENAME,
            decision_out=out_path.parent / DECISION_FILENAME,
        )
    except BaseException as exc:  # noqa: BLE001 - every failure must become a result
        error_type = classify_exception(exc)
        log.write(f"training failed ({error_type}): {type(exc).__name__}: {exc}")
        log.write(traceback.format_exc(limit=6))
        write_result(
            out_path,
            status="error",
            metrics={},
            train_time_sec=time.perf_counter() - started,
            error_type=error_type,
            log_tail=log.tail(),
        )
        return 0

    write_result(
        out_path,
        status="ok",
        metrics=run.metrics,
        train_time_sec=time.perf_counter() - started,
        error_type=None,
        log_tail=log.tail(),
        applied_hyperparams=run.applied,
        dropped_hyperparams=run.dropped,
        applied_preprocessing=run.preprocessing,
        applied_pipeline=run.applied_pipeline,
        model_path=run.model_path,
        schema_path=run.schema_path,
        paired=run.paired,
        internal_validation=run.internal_validation,
    )
    return 0


def _score_only(
    cfg: dict[str, Any], model_path: Path, out_path: Path, log: LogBuffer, started: float
) -> int:
    """The ``--score-model`` path: one pass over the test rows, no fitting, no simulation.

    ``apply_simulation`` is deliberately skipped. A card's failure-injection drill belongs
    to the training attempts it was declared for; re-running it here would fail the final
    measurement of a model that had already trained successfully.
    """
    try:
        metrics, preprocessing = score_saved_model(cfg, log, model_path)
    except BaseException as exc:  # noqa: BLE001 - same contract as the training path
        error_type = classify_exception(exc)
        log.write(f"test scoring failed ({error_type}): {type(exc).__name__}: {exc}")
        log.write(traceback.format_exc(limit=6))
        write_result(
            out_path,
            status="error",
            metrics={},
            train_time_sec=time.perf_counter() - started,
            error_type=error_type,
            log_tail=log.tail(),
            split="test",
        )
        return 0

    write_result(
        out_path,
        status="ok",
        metrics=metrics,
        train_time_sec=time.perf_counter() - started,
        error_type=None,
        log_tail=log.tail(),
        applied_preprocessing=preprocessing,
        split="test",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
