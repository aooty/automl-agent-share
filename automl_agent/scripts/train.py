def goal_metric(cfg: dict[str, Any], task: str, log: LogBuffer | None = None) -> str:
    """The metric this attempt is steered by: the configured one, or this task's default.

    The config's metric can fail to belong to the task in two reachable ways, and neither is
    caught upstream by construction: ``RunConfig`` validates the name against the registry
    before profiling, when nobody knows what the target column is, and the orchestrator's
    substitution (:func:`automl_agent.scoring.goal.resolve_goal`) goes by the *card*, while this
    script goes by the column — a card declaring ``regression`` over a column that reads as
    classification puts the mismatch back inside a consistent-looking run.

    Left alone, the consequences are spread out and each one looks like something else: the
    bootstrap interval is skipped ("split too small, or metric degenerate"), the paired
    comparison against the run's best is skipped as ``degenerate``, the overfitting gap is
    measured on a metric nobody chose, and the schema records a goal metric that a labelled
    batch can never be scored against. Substituting once, here, keeps all four on one number.

    Falls back to this task's default rather than to ``f1``: the old literal was a
    classification metric, so on a regression target it was the same mismatch again.
    """
    configured = canonical(str(cfg.get("metric") or "")) or DEFAULT_METRICS[task]
    swap = substitute_metric(task, configured)
    if swap is None:
        return configured if configured in METRICS else DEFAULT_METRICS[task]
    if log is not None:
        log.write(
            f"metric {configured} is not defined for a {task} target: steering by {swap} "
            f"instead, and recording {swap} in the schema so a labelled batch is scored on "
            "the same number"
        )
    return swap


def load_data(
    cfg: dict[str, Any], log: LogBuffer, schema: dict[str, Any] | None = None
) -> tuple[Any, Any, int, Any, str, dict[str, Any] | None]:
    """Return ``(X, y, n_classes, groups, task, schema)`` from a CSV path, or synthesise.

    The agent is given a *dataset card*, not the raw data. When no ``path`` is
    supplied we generate a dataset matching the card's declared shape so the whole
    pipeline is runnable end to end.

    ``groups`` is ``None`` unless ``data.group_column`` names a column, in which case it
    is that column's values aligned to the returned rows — dropped from the features
    first, because an identifier the estimator can read is a shortcut to the label, and a
    numeric one (``subject_id``) would otherwise survive :func:`encode_features` as a
    perfectly ordinary feature.

    ``task`` is read off the target column by :func:`automl_agent.dataset.targets.detect_task` — the
    same function the profiler used when it wrote the card, so the two processes agree about
    what is being predicted without having to be told twice. ``n_classes`` is ``0`` for a
    regression target: there are none, and every consumer here already branches on the task.
    On the synthetic path there is no column to read, so the config's declared ``task``
    decides which generator runs.

    The returned ``schema`` is the encoding that produced ``X`` — the ordered encoded columns,
    each categorical column's levels, and what each class code means — so the caller can save
    it beside the fitted model. ``None`` on the synthetic path, where the matrix is generated
    rather than encoded and there is nothing to replay it on.

    Passing a ``schema`` in reverses the direction: the file is encoded to *that* layout
    instead of to whatever layout it implies on its own. That is what makes a saved model
    scoreable — see :func:`automl_agent.dataset.features.encode_with_schema`. It is used on the
    ``--score-model`` path, where the alternative is re-deriving the layout from a file that
    may no longer be the one the fit saw, and getting a matrix that is silently misaligned
    rather than an error.
    """
    import numpy as np

    data = dict(cfg.get("data") or {})
    path = data.get("path")
    seed = int(cfg.get("seed", 42))
    group_column = data.get("group_column")
    declared_task = str(cfg.get("task") or TASK_CLASSIFICATION)

    if path:
        import pandas as pd

        target = str(data.get("target_column") or "target")
        frame = pd.read_csv(path)
        if target not in frame.columns:
            raise ValueError(f"target_column {target!r} not found in {path}")
        y_series = frame[target]
        group_series = None
        drop = [target]
        if group_column:
            group_column = str(group_column)
            if group_column not in frame.columns:
                raise ValueError(f"group_column {group_column!r} not found in {path}")
            if group_column == target:
                raise ValueError(f"group_column {group_column!r} is the target column")
            group_series = frame[group_column]
            drop.append(group_column)
        # The same encoding the profiler applied before measuring the baseline, from the
        # same function — a bar derived from one feature matrix and scores measured on
        # another are not comparable.
        raw_features = frame.drop(columns=drop)
        if schema is None:
            features, encoding = encode_features(raw_features)
            log.write(describe_encoding(encoding))
            fitted_schema: dict[str, Any] | None = build_schema(raw_features)
        else:
            features, drift = encode_with_schema(raw_features, schema)
            for line in describe_drift(drift):
                log.write(line)
            fitted_schema = dict(schema)
        if features.shape[1] == 0:
            raise ValueError("no usable feature columns remain after dropping the target")
        # Same policy the card recorded, so the profiler's baseline and this score are
        # measured over the same rows. NaN never becomes a class of its own.
        policy = str((cfg.get("target_missing") or {}).get("policy") or DEFAULT_TARGET_MISSING_POLICY)
        task = detect_task(y_series)
        if task != declared_task:
            # Not fatal: the column is the authority and the card is a description of it.
            # Worth a line, because it means the file changed under the card and the
            # baseline the bar came from was measured on the other reading of this column.
            log.write(
                f"target column reads as {task}, but the config declares {declared_task}; "
                "following the column"
            )
        codes, keep, n_missing = encode_target(y_series, policy, task)
        if n_missing:
            features = features[keep]
            if group_series is not None:
                group_series = group_series[keep]
            log.write(f"dropped {n_missing} rows with a missing target (policy={policy})")
        log.write(f"loaded {path}: {features.shape[0]} rows x {features.shape[1]} encoded features")
        groups = None
        if group_series is not None:
            # As text, so a float id and an int id of the same patient are one group and
            # NaN does not silently become a group of one row per NaN.
            groups = group_series.astype("string").fillna("<missing>").to_numpy()
            log.write(f"grouped by {group_column}: {len(set(groups.tolist()))} distinct groups")
        y_codes = codes.to_numpy()
        x_arr = np.asarray(features.to_numpy(), dtype="float64")
        goal = goal_metric(cfg, task, log)
        if fitted_schema is not None:
            # Everything ``predict`` needs that is not in the estimator: which column of the
            # matrix was which, what the numbers coming out of it mean, and which columns the
            # file must not be allowed to supply because the fit never saw them as features.
            fitted_schema.update(
                {
                    "task": task,
                    "target_column": target,
                    "group_column": group_column,
                    "classes": target_classes(y_series, task),
                    "n_features": int(x_arr.shape[1]),
                    "seed": seed,
                    # The metric this run was steered by, so a later labelled batch is scored
                    # on the same number the run was optimised for rather than on whatever
                    # the person scoring the batch happens to pick. Without it, "0.71 on the
                    # holdout, 0.64 here" could be two different measurements.
                    "metric": goal,
                }
            )
        return (
            x_arr,
            y_codes,
            0 if task == TASK_REGRESSION else int(len(set(y_codes.tolist()))),
            groups,
            task,
            fitted_schema,
        )

    syn = dict(data.get("synthetic") or {})
    n_samples = int(syn.get("n_samples", 5000))
    n_features = int(syn.get("n_features", 20))
    n_informative = int(syn.get("n_informative", max(2, n_features // 2)))
    n_informative = min(n_informative, n_features)

    if declared_task == TASK_REGRESSION:
        from sklearn.datasets import make_regression

        x_arr, y_arr = make_regression(
            n_samples=n_samples,
            n_features=n_features,
            n_informative=n_informative,
            # The regression counterpart of ``flip_y``: irreducible error, so a synthetic
            # run cannot reach r2=1.0 and the loop has something to actually converge on.
            noise=float(syn.get("noise", 10.0)),
            random_state=seed,
        )
        log.write(
            f"synthesised regression dataset from card: {n_samples} rows x {n_features} "
            f"features, noise={syn.get('noise', 10.0)}"
        )
        return x_arr, y_arr, 0, None, TASK_REGRESSION, None

    from sklearn.datasets import make_classification

    n_classes = int(syn.get("n_classes", 2))
    weights = syn.get("class_weights")
    x_arr, y_arr = make_classification(
        n_samples=n_samples,
        n_features=n_features,
        n_informative=n_informative,
        n_redundant=max(0, min(n_features - n_informative, int(syn.get("n_redundant", 2)))),
        n_classes=n_classes,
        n_clusters_per_class=int(syn.get("n_clusters_per_class", 2)),
        weights=list(weights) if weights else None,
        class_sep=float(syn.get("class_sep", 0.8)),
        flip_y=float(syn.get("flip_y", 0.03)),
        random_state=seed,
    )
    log.write(
        f"synthesised dataset from card: {n_samples} rows x {n_features} features, "
        f"{n_classes} classes, class_sep={syn.get('class_sep', 0.8)}, flip_y={syn.get('flip_y', 0.03)}"
    )
    return x_arr, y_arr, n_classes, None, TASK_CLASSIFICATION, None


def guard_memory(x_arr: Any, cfg: dict[str, Any], log: LogBuffer) -> None:
    """Raise ``MemoryError`` when the working set would exceed the declared budget.

    A real GPU run would surface CUDA OOM here. On CPU/tabular we enforce an
    explicit budget instead, so the ``oom`` branch is reachable and testable
    rather than hypothetical. ``batch_size`` shrinks the estimate, which is what
    makes the Critic's "reduce batch size" advice actually pay off.
    """
    limit_mb = cfg.get("memory_limit_mb")
    if not limit_mb:
        return
    rows, cols = int(x_arr.shape[0]), int(x_arr.shape[1])
    hyperparams = dict(cfg.get("hyperparams") or {})
    batch = hyperparams.get("batch_size")
    working_rows = min(rows, int(batch)) if isinstance(batch, int) and batch > 0 else rows
    # Tree ensembles and MLPs hold several copies of the working set.
    copies = 4 if cfg.get("model") in {"random_forest", "extra_trees", "gradient_boosting"} else 2
    if str(hyperparams.get("precision", "")).lower() in {"fp16", "float16", "half"}:
        copies = max(1, copies // 2)
    estimate_mb = working_rows * cols * 8 * copies / (1024 * 1024)
    log.write(f"memory estimate {estimate_mb:.1f} MB vs budget {float(limit_mb):.1f} MB")
    if estimate_mb > float(limit_mb):
        raise MemoryError(
            f"out of memory: estimated {estimate_mb:.1f} MB exceeds budget {float(limit_mb):.1f} MB"
        )


