def weight_map(value: dict[Any, Any], labels: Sequence[Any] | None) -> dict[int, float] | None:
    """A ``class_weight`` mapping sklearn will accept, or ``None`` when it will not.

    Two repairs, both of which used to be fatal or silent:

    * **JSON has no integer keys.** The config reaches this script through
      ``train_config.json``, so ``{0: 1, 1: 10}`` arrives as ``{"0": 1, "1": 10}`` and
      sklearn rejects string keys against integer labels.
    * **A label the data does not have raises inside ``fit``**, i.e. after the pipeline is
      built and the memory guard has passed, which costs the whole iteration. Requiring
      exactly one weight per present label turns that into an ordinary dropped
      hyperparameter instead.

    Keys are class *codes*: ``targets.encode_target`` hands training category codes
    (0..n_classes-1, the order of the card's ``class_balance``), not the raw labels.
    """
    if not value:
        return None
    clean: dict[int, float] = {}
    for raw_code, raw_weight in value.items():
        if isinstance(raw_code, bool) or isinstance(raw_weight, bool):
            return None
        try:
            code = int(str(raw_code).strip())
            weight = float(raw_weight)
        except (TypeError, ValueError):
            return None
        if not math.isfinite(weight) or weight <= 0 or code in clean:
            return None
        clean[code] = weight
    if labels is not None and set(clean) != {int(label) for label in labels}:
        return None
    return clean


