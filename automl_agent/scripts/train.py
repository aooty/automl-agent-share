def evaluate_split(
    model: Any,
    x_eval: Any,
    y_eval: Any,
    n_classes: int,
    average: str,
    log: LogBuffer,
    *,
    task: str = TASK_CLASSIFICATION,
    interval_metric: str | None = None,
    groups: Any = None,
    seed: int = 42,
    resamples: int = DEFAULT_RESAMPLES,
    pred: Any = None,
    proba: Any = None,
) -> dict[str, float]:
    """Every registry metric this prediction supports, plus the binary diagnostics.

    Shared by the validation scoring inside :func:`run_training` and the one-shot test
    scoring in :func:`score_saved_model`, so the two numbers a report puts side by side
    are computed by the same code over different rows.

    ``interval_metric`` names the one metric that also gets a bootstrap confidence interval
    — the goal metric, because it is the number every comparison in the run is made
    against and the cost is linear in metrics times resamples. ``groups`` is the eval
    split's group labels, so a clustered split is resampled by group rather than by row
    (:mod:`automl_agent.scoring.intervals`).

    ``pred``/``proba`` let a caller hand in the predictions instead of having them computed
    here. The one caller that does is :func:`run_training`, which has to *save* the arrays
    for a later attempt to pair against: predicting twice would put two sources under one
    filename, and the file would then describe a pass that nothing was scored on.
    """
    if pred is None:
        pred = model.predict(x_eval)
        proba = _proba(model, x_eval, n_classes, log)
    metrics = score_split(list(METRICS), y_eval, pred, proba, average, log, task)
    for alias, canonical_name in METRIC_ALIASES.items():
        if canonical_name in metrics:
            metrics[alias] = metrics[canonical_name]

    # The other half of balanced_accuracy. Emitted for every binary attempt, not only when
    # balanced_accuracy is the goal, because it costs one more scorer call and it is the
    # number that turns "the operating point is off" into "the weight has to go up".
    if n_classes == 2:
        metrics["specificity"] = round(specificity(y_eval, pred), 6)

    # What choosing the decision threshold would have been worth, in the metric's own
    # units. Every real LLM run has planned a threshold sweep, and the executor cannot do
    # one — but the reason to refuse is quantitative, and nothing was ever measuring it.
    # ``(1 + KS) / 2`` is the best balanced_accuracy any cut of this ranking allows
    # (automl_agent.scoring.ranking), so the difference is exactly the size of the prize. On the
    # MIMIC sample it is +0.0024, which is what turns "the executor will not do that" into
    # "that would buy 0.002; the ranking is where the rest of the gap is".
    #
    # A diagnostic, like specificity and train_val_gap. Never targetable: it is measured
    # at a cut the executor will not apply, so a goal set against it could not be met by
    # anything the harness actually runs.
    ceiling = best_cut_ceiling(ks_statistic(y_eval, proba))
    if ceiling is not None:
        best_cut, headroom = CUT_DIAGNOSTICS
        metrics[best_cut] = ceiling
        if "balanced_accuracy" in metrics:
            metrics[headroom] = round(ceiling - metrics["balanced_accuracy"], 6)

    # Whether the probabilities in the output CSV mean what they say. Every metric above is
    # about the ranking or about the 0/1 call at sklearn's fixed 0.5 cut, and a model can be
    # perfect on both while being systematically overconfident — which matters here precisely
    # because the harness refuses to choose a threshold, so the probability is the part a
    # caller acts on with their own. Diagnostic on the same terms as the two above: measured,
    # reported, never targetable, and never fed back as a recalibration
    # (:mod:`automl_agent.scoring.calibration`).
    if proba is not None:
        metrics.update(calibration_measure(y_eval, proba))

    # How wide the goal metric is on these rows. ``--metric`` only accepts registry keys
    # (``metrics.GOAL_METRICS``), so no alias mirroring is needed here — the interval is
    # published under the same name the goal is stated in.
    target = canonical(interval_metric) if interval_metric else None
    if target and target in metrics:

        def one(y_slice: Any, pred_slice: Any, proba_slice: Any) -> float:
            return float(scorers(y_slice, pred_slice, proba_slice, average, task)[str(target)]())

        interval = bootstrap_interval(
            one, y_eval, pred, proba, groups=groups, seed=seed, resamples=resamples
        )
        if interval is None:
            log.write(f"{target}: no confidence interval (split too small, or metric degenerate)")
        else:
            metrics.update(interval.flatten(target))
            log.write(
                describe_interval(target, metrics[target], interval.bounds)
                + f" — {interval.unit} 단위 재표집 {interval.resamples}회"
            )
    return metrics


def save_model(model: Any, path: Path, log: LogBuffer) -> str | None:
    """Persist the fitted pipeline; return its path, or ``None`` if it could not be written.

    Never fatal. The score has already been earned by the time this runs, and losing the
    run over a full disk would be a worse failure than losing the file. The final holdout
    scoring degrades to "skipped" in that case (``nodes/holdout.py``).

    The file stays inside the run's artifact directory, which ``.gitignore`` blocks, and
    its path is not part of ``privacy.PUBLIC_RESULT_FIELDS``. That is deliberate rather
    than tidy: a fitted ``SVC`` stores its support vectors and a tree stores thresholds
    read off real values, so a model file is data-equivalent and belongs on the private
    side of the boundary with the raw rows.
    """
    try:
        import joblib

        path.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(model, path)
    except (OSError, ImportError, TypeError, ValueError) as exc:
        log.write(f"model not saved: {type(exc).__name__}: {exc}")
        return None
    size = path.stat().st_size
    line = f"model saved to {path.name} ({file_size_text(size)})"
    if size > LARGE_MODEL_BYTES:
        # The hyperparameters an iteration was given decide this, and nothing else looks at
        # it: ``guard_memory`` prices the input matrix, which is the same size whatever the
        # estimator does with it. A forest with unbounded depth over 47k rows wrote 486 MB in
        # one iteration of a real run, so on a five-iteration loop the disk is the real limit.
        line += (
            f" — over {file_size_text(LARGE_MODEL_BYTES)}, driven by this iteration's "
            "hyperparameters (tree count and depth, mostly). The run keeps it; the disk is "
            "what bounds a long loop, not memory"
        )
    log.write(line)
    return str(path)




def save_schema(schema: dict[str, Any] | None, path: Path, log: LogBuffer) -> str | None:
    """Persist the encoding the model was fitted with; return its path, or ``None``.

    Never fatal, on the same terms as :func:`save_model`. What is lost without it is narrower
    and worth naming: the model file alone cannot say which column of its input was which, so
    a model saved without its schema can only be applied to rows that happen to encode into
    the same layout — and nothing would check that they had. ``predict`` refuses to run rather
    than guess, which is the point of writing this at all.

    ``None`` schema is not an error: the synthetic path generates its matrix instead of
    encoding a file, so there is no encoding to replay and nothing to write.

    Data-equivalent — category levels and class labels are cell values — so it lands inside
    ``artifacts/`` beside the model and its path stays out of
    ``privacy.PUBLIC_RESULT_FIELDS``.
    """
    if schema is None:
        return None
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(schema, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    except (OSError, TypeError, ValueError) as exc:
        log.write(f"feature schema not saved: {type(exc).__name__}: {exc}")
        return None
    log.write(f"feature schema saved to {path.name} ({len(schema.get('columns') or ())} columns)")
    return str(path)


def load_schema(path: Path, log: LogBuffer) -> dict[str, Any] | None:
    """Read a schema saved beside a model, or ``None`` when there is not one to read.

    ``None`` covers two cases that both have to keep working: a synthetic run, where no
    encoding was ever fitted, and a run from before this file was written. Both fall back to
    re-deriving the layout, which is what they did all along.

    An unreadable or malformed file is *not* silently treated as absent — that would turn a
    corrupted schema into a scoring run whose columns line up by width alone, which is exactly
    the failure this artifact exists to prevent.
    """
    if not path.exists():
        log.write(f"no feature schema beside the model ({path.name}); deriving the encoding from the file")
        return None
    loaded = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        raise ValueError(f"feature schema {path} is not a JSON object")
    log.write(f"encoding from {path.name}: {len(loaded.get('columns') or ())} columns")
    return loaded


def save_predictions(
    path: Path, pred: Any, proba: Any, fingerprint: str, log: LogBuffer
) -> str | None:
    """Persist this attempt's validation-row predictions, so a later one can pair against it.

    Never fatal, for the same reason :func:`save_model` is not: the score has been earned by
    the time this runs, and the only thing lost is a later attempt's paired verdict, which
    degrades to ``skipped`` with a reason.

    One value per validation row, so this file is data-equivalent in exactly the way
    ``model.joblib`` is, and it stays on the same side of the boundary: written inside
    ``artifacts/``, its *contents* never enter a state channel, and even its path is derived
    from the iteration number rather than carried in one
    (:meth:`automl_agent.config.RunConfig.predictions_path`).

    ``y_val`` is deliberately not in the file. The process that pairs against it has the
    labels already — it just split the same rows — and the fingerprint is what establishes
    that they are the same rows. Storing them would be one more copy of the target column on
    disk buying nothing.
    """
    try:
        import numpy as np

        path.parent.mkdir(parents=True, exist_ok=True)
        arrays: dict[str, Any] = {
            "pred": np.asarray(pred),
            "fingerprint": np.asarray(str(fingerprint)),
        }
        if proba is not None:
            arrays["proba"] = np.asarray(proba)
        np.savez_compressed(path, **arrays)
    except (OSError, ImportError, TypeError, ValueError) as exc:
        log.write(f"val predictions not saved: {type(exc).__name__}: {exc}")
        return None
    log.write(f"val predictions saved to {path.name} ({path.stat().st_size / 1024:.0f} KB)")
    return str(path)


def paired_against_baseline(
    cfg: dict[str, Any],
    y_val: Any,
    pred: Any,
    proba: Any,
    fingerprint: str,
    *,
    metric: str,
    average: str,
    task: str,
    log: LogBuffer,
    groups: Any = None,
    seed: int = 42,
) -> dict[str, Any]:
    """This attempt's goal metric against the run's best so far, as a resampled difference.

    Computed in this process rather than in the node that reads the result, and for the same
    reason ``scripts/train.py`` is a subprocess at all: the orchestrator never imports numpy
    or sklearn, so no node can resample anything. The other option — a second subprocess per
    iteration, the way :mod:`automl_agent.nodes.holdout` scores the test split — would have
    to rebuild this split from the config, and a second derivation is a second thing that can
    disagree with the first. Here ``y_val``, ``pred`` and ``proba`` are the arrays that were
    just scored, so there is nothing to re-derive.

    Always returns a block, and a skipped comparison publishes *why*: "no paired verdict" and
    "the paired verdict found nothing" are different facts, and a reader given silence for
    the first would take it for the second.
    """
    declared = dict(cfg.get("paired_baseline") or {})
    iteration = declared.get("iteration")
    raw_path = declared.get("path")
    block: dict[str, Any] = {"metric": metric, "baseline_iteration": iteration}

    def skipped(reason: str, detail: str = "") -> dict[str, Any]:
        log.write(f"paired comparison skipped ({reason}){f': {detail}' if detail else ''}")
        return {**block, "status": PAIRED_SKIPPED, "reason": reason}

    if not raw_path or iteration is None:
        return skipped("no_baseline")

    import numpy as np

    path = Path(str(raw_path))
    try:
        # ``allow_pickle=False``: this file is written by this script and read by it, and a
        # pickle-bearing npz in the artifact directory would be code execution dressed as a
        # measurement.
        with np.load(path, allow_pickle=False) as loaded:
            stored = str(loaded["fingerprint"])
            base_pred = np.asarray(loaded["pred"])
            base_proba = np.asarray(loaded["proba"]) if "proba" in loaded.files else None
    except (OSError, ValueError, KeyError) as exc:
        return skipped("baseline_missing", f"{path.name}: {type(exc).__name__}: {exc}")

    if stored != fingerprint:
        # The premise of the whole comparison, checked rather than asserted from the seed —
        # see :func:`automl_agent.scoring.splits.val_fingerprint` for what changes the rows without
        # changing the seed.
        return skipped("split_changed", f"{stored[:8]} != {fingerprint[:8]}")

    spec = METRICS.get(metric)
    if spec is not None and spec.needs_proba and (proba is None or base_proba is None):
        return skipped("degenerate", f"{metric} needs probabilities and one side has none")

    def one(y_slice: Any, pred_slice: Any, proba_slice: Any) -> float:
        return float(scorers(y_slice, pred_slice, proba_slice, average, task)[metric]())

    delta = paired_delta(
        one,
        y_val,
        (pred, proba),
        (base_pred, base_proba),
        direction=direction_of(metric),
        groups=groups,
        seed=seed,
        resamples=bootstrap_resamples(cfg),
    )
    if delta is None:
        return skipped("degenerate", f"{metric}: no interval over the difference")
    measured = {
        **block,
        "status": PAIRED_MEASURED,
        "resamples": delta.resamples,
        "unit": delta.unit,
        **delta.flatten(),
    }
    log.write(f"{metric} vs iteration {iteration}: {describe_paired(measured)}")
    return measured


def run_training(
    cfg: dict[str, Any],
    log: LogBuffer,
    model_out: Path | None = None,
    predictions_out: Path | None = None,
    schema_out: Path | None = None,
) -> tuple[
    dict[str, float], dict[str, Any], list[str], dict[str, Any], str | None, dict[str, Any], str | None
]:
    """Fit and score. ``(metrics, applied, dropped, preprocessing, model_path, paired, schema_path)``.

    Three of those seven say what the run was *configured* with rather than what it scored,
    and they are returned rather than re-derived because only this function saw the
    estimator: the config is a request the executor is allowed to narrow. ``paired`` is the
    comparison against the run's best so far, which is empty unless the caller asked for one
    (:func:`paired_against_baseline`). ``schema_path`` is the other half of ``model_path`` —
    the encoding that model was fitted with, without which it can be loaded but not applied.

    Scores are validation-set scores: the test slice
    (:mod:`automl_agent.scoring.splits`) is not read here at all, so nothing the loop selects on
    can have touched it.
    """
    seed = int(cfg.get("seed", 42))
    x_arr, y_arr, n_classes, groups, task, schema = load_data(cfg, log)
    guard_memory(x_arr, cfg, log)
    regression = task == TASK_REGRESSION

    group_column = (cfg.get("data") or {}).get("group_column")
    splits = split_three_way(x_arr, y_arr, seed, groups=groups, stratify=not regression)
    x_train, y_train = splits.x_train, splits.y_train
    x_val, y_val = splits.x_val, splits.y_val
    log.write(
        describe_protocol(protocol(seed, group_column, stratified=not regression))
        + f" {splits.sizes}"
    )

    subsample = (cfg.get("hyperparams") or {}).get("train_subsample")
    if isinstance(subsample, (int, float)) and 0 < float(subsample) < 1:
        keep = max(50, int(len(x_train) * float(subsample)))
        x_train, y_train = x_train[:keep], y_train[:keep]
        log.write(f"train_subsample={subsample} -> {keep} rows")

    model, applied, dropped = build_estimator(
        str(cfg.get("model") or "hist_gbdt"),
        dict(cfg.get("hyperparams") or {}),
        seed,
        log,
        dict(cfg.get("preprocessing") or {}),
        # The labels a ``class_weight`` map has to cover exactly. Taken from the training
        # split, which is what sklearn will validate the map against. ``None`` for a
        # continuous target: there are no classes to weight, and enumerating every distinct
        # value of the column would be both useless and a set of cell values.
        labels=None if regression else sorted(set(y_train.tolist())),
        task=task,
    )
    log.write(f"fitting on {len(x_train)} rows, validating on {len(x_val)} rows")
    model.fit(x_train, y_train)
    model_path = save_model(model, model_out, log) if model_out is not None else None
    # Written after the fit and beside the model, so the file on disk describes the encoding
    # of the matrix this estimator actually saw rather than one derived separately later.
    schema_path = save_schema(schema, schema_out, log) if schema_out is not None else None

    # Silent here: ``load_data`` above already logged the substitution if there was one, and
    # this is the same call with the same task.
    target_metric = goal_metric(cfg, task)
    average = "binary" if n_classes == 2 else "macro"
    pred_train = model.predict(x_train)
    # Predicted once, here, and then both scored and saved. The arrays a later iteration
    # pairs against have to be the arrays this iteration's metrics were computed from, or the
    # file describes a pass nothing was scored on.
    pred_val = model.predict(x_val)
    proba_val = _proba(model, x_val, n_classes, log)
    metrics = evaluate_split(
        model,
        x_val,
        y_val,
        n_classes,
        average,
        log,
        task=task,
        interval_metric=target_metric,
        # The validation split's own group labels, not the whole file's: this interval is
        # about the rows the score was measured on.
        groups=splits.groups_val,
        seed=seed,
        resamples=bootstrap_resamples(cfg),
        pred=pred_val,
        proba=proba_val,
    )

    fingerprint = val_fingerprint(x_val, y_val)
    if predictions_out is not None:
        save_predictions(predictions_out, pred_val, proba_val, fingerprint, log)
    paired = paired_against_baseline(
        cfg,
        y_val,
        pred_val,
        proba_val,
        fingerprint,
        metric=target_metric,
        average=average,
        task=task,
        log=log,
        groups=splits.groups_val,
        seed=seed,
    )

    # Train scores let the Critic tell underfitting from overfitting. The task's two default
    # metrics are part of result.json's shape whatever the goal metric is; the goal metric is
    # added because the gap below has to be about the number the run is judged on.
    train_names = list(TRAIN_METRICS[task])
    if target_metric in METRICS and target_metric not in train_names:
        train_names.append(target_metric)
    train_proba = (
        _proba(model, x_train, n_classes, log)
        if any(METRICS[name].needs_proba for name in train_names)
        else None
    )
    for name, value in score_split(
        train_names, y_train, pred_train, train_proba, average, log, task
    ).items():
        metrics[f"train_{name}"] = value

    # Defined on the goal metric, not on the task's first default: the Critic's
    # overfitting/underfitting branches read this one number, and a gap measured on a metric
    # nobody is optimising sends it the wrong diagnosis. The fallback is for a goal metric
    # with no train counterpart (a probability metric on a model without predict_proba).
    fallback_gap_metric = TRAIN_METRICS[task][0]
    gap_metric = target_metric if f"train_{target_metric}" in metrics else fallback_gap_metric
    if gap_metric in metrics and f"train_{gap_metric}" in metrics:
        # Always "how much worse validation is than training", never a bare subtraction: on a
        # minimize metric the train score is the *smaller* number, so ``train - val`` would be
        # negative exactly when the model is overfitting. Every consumer reads a positive gap
        # as overfitting (``nodes/critic.py``, the Critic prompt's rules), so the direction is
        # applied here — one place — rather than in each of them.
        train_value, val_value = metrics[f"train_{gap_metric}"], metrics[gap_metric]
        worse_by = (
            val_value - train_value
            if direction_of(gap_metric) == MINIMIZE
            else train_value - val_value
        )
        metrics["train_val_gap"] = round(worse_by, 6)
        log.write(f"train_val_gap measured on {gap_metric} ({direction_of(gap_metric)})")

    log.write("metrics: " + json.dumps({k: round(v, 4) for k, v in metrics.items()}))
    return (
        metrics,
        applied,
        dropped,
        describe_preprocessing(model),
        model_path,
        paired,
        schema_path,
    )


def score_saved_model(
    cfg: dict[str, Any], log: LogBuffer, model_path: Path
) -> tuple[dict[str, float], dict[str, Any]]:
    """Score the held-back test split with a model fitted in an earlier process.

    Nothing is fitted here, and nothing but ``x_test`` is predicted on: the point of the
    number is that no decision in the run was made against these rows. The split is
    rebuilt rather than stored, which is safe because it is a pure function of the file,
    the target policy, the group column and the seed — all of which come from the same
    ``train_config.json`` the fit used.

    The preprocessing comes back alongside the metrics because it is read off the loaded
    pipeline: this process never built one, so the config is the only other source and the
    config is a request, not a record.

    The encoding comes off disk too, from the schema saved beside the model, so the test rows
    are encoded into the layout this estimator was fitted on. Re-deriving it from the file
    would agree in the ordinary case and disagree silently in the case worth catching — a file
    edited between the fit and the holdout, whose columns then line up by width alone. A run
    from before schemas were saved has no such file; it is scored the old way, with a line in
    the log saying so.
    """
    import joblib

    seed = int(cfg.get("seed", 42))
    schema = load_schema(model_path.parent / SCHEMA_FILENAME, log)
    x_arr, y_arr, n_classes, groups, task, _schema = load_data(cfg, log, schema)
    splits = split_three_way(
        x_arr, y_arr, seed, groups=groups, stratify=task != TASK_REGRESSION
    )
    model = joblib.load(model_path)
    average = "binary" if n_classes == 2 else "macro"
    log.write(
        f"scoring the held-back test split: {len(splits.y_test)} rows, "
        f"model={model_path.name}"
    )
    metrics = evaluate_split(
        model,
        splits.x_test,
        splits.y_test,
        n_classes,
        average,
        log,
        task=task,
        interval_metric=canonical(str(cfg.get("metric") or "f1")),
        groups=splits.groups_test,
        seed=seed,
        resamples=bootstrap_resamples(cfg),
    )
    log.write("test metrics: " + json.dumps({k: round(v, 4) for k, v in metrics.items()}))
    return metrics, describe_preprocessing(model)


