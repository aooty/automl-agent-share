def _classifier(key: str, seed: int) -> Any:
    """The classifier this key names, or ``None`` if it names none."""
    if key == "logreg":
        from sklearn.linear_model import LogisticRegression

        return LogisticRegression(max_iter=1000, random_state=seed)
    if key == "random_forest":
        from sklearn.ensemble import RandomForestClassifier

        return RandomForestClassifier(n_estimators=300, n_jobs=-1, random_state=seed)
    if key == "extra_trees":
        from sklearn.ensemble import ExtraTreesClassifier

        return ExtraTreesClassifier(n_estimators=300, n_jobs=-1, random_state=seed)
    if key == "hist_gbdt":
        from sklearn.ensemble import HistGradientBoostingClassifier

        return HistGradientBoostingClassifier(random_state=seed)
    if key == "gradient_boosting":
        from sklearn.ensemble import GradientBoostingClassifier

        return GradientBoostingClassifier(random_state=seed)
    if key == "decision_tree":
        from sklearn.tree import DecisionTreeClassifier

        return DecisionTreeClassifier(random_state=seed)
    if key == "knn":
        from sklearn.neighbors import KNeighborsClassifier

        return KNeighborsClassifier()
    if key == "svc":
        from sklearn.svm import SVC

        return SVC(random_state=seed)
    if key == "mlp":
        from sklearn.neural_network import MLPClassifier

        return MLPClassifier(max_iter=400, random_state=seed)
    if key == "xgboost":
        try:
            from xgboost import XGBClassifier
        except ImportError as exc:  # pragma: no cover - reached only if the extra is missing
            raise ValueError(f"model 'xgboost' is unavailable: {exc}") from exc

        return XGBClassifier(
            n_estimators=300, tree_method="hist", eval_metric="logloss", random_state=seed
        )
    return None


def _regressor(key: str, seed: int) -> Any:
    """The regressor this key names, or ``None`` if it names none.

    Deliberately the same keys as :func:`_classifier` wherever the family exists on both
    sides — ``hist_gbdt`` is the same word for both, so a plan written against one card
    reads the same way against the other, and ``capabilities`` publishes one vocabulary.
    """
    if key == "linreg":
        from sklearn.linear_model import LinearRegression

        # No ``random_state``: the closed-form solution has nothing to seed.
        return LinearRegression()
    if key == "ridge":
        from sklearn.linear_model import Ridge

        return Ridge(random_state=seed)
    if key == "elasticnet":
        from sklearn.linear_model import ElasticNet

        return ElasticNet(random_state=seed)
    if key == "random_forest":
        from sklearn.ensemble import RandomForestRegressor

        return RandomForestRegressor(n_estimators=300, n_jobs=-1, random_state=seed)
    if key == "extra_trees":
        from sklearn.ensemble import ExtraTreesRegressor

        return ExtraTreesRegressor(n_estimators=300, n_jobs=-1, random_state=seed)
    if key == "hist_gbdt":
        from sklearn.ensemble import HistGradientBoostingRegressor

        return HistGradientBoostingRegressor(random_state=seed)
    if key == "gradient_boosting":
        from sklearn.ensemble import GradientBoostingRegressor

        return GradientBoostingRegressor(random_state=seed)
    if key == "decision_tree":
        from sklearn.tree import DecisionTreeRegressor

        return DecisionTreeRegressor(random_state=seed)
    if key == "knn":
        from sklearn.neighbors import KNeighborsRegressor

        return KNeighborsRegressor()
    if key == "svr":
        from sklearn.svm import SVR

        return SVR()
    if key == "mlp":
        from sklearn.neural_network import MLPRegressor

        return MLPRegressor(max_iter=400, random_state=seed)
    if key == "xgboost":
        try:
            from xgboost import XGBRegressor
        except ImportError as exc:  # pragma: no cover - reached only if the extra is missing
            raise ValueError(f"model 'xgboost' is unavailable: {exc}") from exc

        return XGBRegressor(n_estimators=300, tree_method="hist", random_state=seed)
    return None


def build_estimator(
    name: str,
    hyperparams: dict[str, Any],
    seed: int,
    log: LogBuffer,
    preprocessing: dict[str, Any] | None = None,
    labels: Sequence[Any] | None = None,
    task: str = TASK_CLASSIFICATION,
) -> tuple[Any, dict[str, Any], list[str]]:
    """Instantiate the named model, then apply only the params it actually accepts.

    Unknown keys are dropped and logged rather than raising: the LLM proposes,
    this code validates. That is the reasoning/execution split in practice.

    Returns ``(pipeline, applied, dropped)``. The narrowing used to be visible only in
    ``train.log``, so the report printed the *proposal* and called it the configuration
    that produced the score. Handing both dicts back is what lets the record state what
    actually ran, under the sklearn parameter names it ran under.

    ``task`` selects which of the two estimator families the name is resolved in. A name
    that exists only in the other one raises ``unsupported model``, which
    :func:`classify_exception` turns into an ``unsupported_model`` result — a diagnosable
    outcome, unlike a classifier quietly fitted to a continuous target.
    """
    key = name.strip().lower().replace("-", "_")
    key = MODEL_ALIASES.get(task, {}).get(key, key)

    model = _regressor(key, seed) if task == TASK_REGRESSION else _classifier(key, seed)
    if model is None:
        raise ValueError(f"unsupported model {name!r} for a {task} target")

    mapped: dict[str, Any] = {}
    dropped: list[str] = []
    accepted = model.get_params(deep=False)
    blocked = UNSUPPORTED_BY_HARNESS.get(key, ())
    for raw_key, value in hyperparams.items():
        param = ALIASES.get(key, {}).get(raw_key, raw_key)
        if param in blocked:
            dropped.append(raw_key)
            continue
        if param == "class_weight" and isinstance(value, dict):
            repaired = weight_map(value, labels)
            if repaired is None:
                log.write(f"dropped class_weight={value!r}: not one positive weight per class")
                dropped.append(raw_key)
                continue
            value = repaired
        if param in accepted:
            if param == "hidden_layer_sizes" and isinstance(value, list):
                value = tuple(value)
            mapped[param] = value
        else:
            dropped.append(raw_key)
    if mapped:
        try:
            model.set_params(**mapped)
        except (ValueError, TypeError) as exc:
            log.write(f"rejected hyperparams {mapped}: {exc}; falling back to defaults")
            mapped = {}
    if dropped:
        log.write(f"dropped hyperparams not applicable to {key}: {sorted(dropped)}")
    log.write(f"estimator={key} applied_hyperparams={mapped}")
    return _wrap_preprocessing(key, model, preprocessing or {}, log), mapped, sorted(dropped)


# What the config may ask SimpleImputer for. The planning side validates this too
# (``nodes/training.py::preprocessing_block``); repeating it here is what makes the
# script safe to run against a hand-written config.
IMPUTE_STRATEGIES = ("median", "mean", "most_frequent")
DEFAULT_IMPUTE = "median"
# Not a SimpleImputer strategy — it removes the step entirely. Honoured only for
# :data:`NATIVE_NAN`, so a card can hand a tree the NaNs it knows how to split on instead
# of a median that erases which rows were measured.
IMPUTE_NONE = "none"

# The two columns missingness can become. Both run *before* the imputer, which is the whole
# point: after it there is nothing left to mark. The transformers themselves are
# :func:`automl_agent.dataset.features.append_missing_indicator` and its counterpart — deliberately
# not defined in this module, because this one runs as ``__main__`` and a pickled pipeline
# would record that as the function's home. See the comment there.
MISSING_INDICATOR = "missing_indicator"
MISSING_COUNT = "missing_count"
# Names the executor answers to besides the canonical ones. sklearn calls the parameter
# ``add_indicator`` and the class ``MissingIndicator``, so which name a plan reaches for is
# close to a coin flip, and an unrecognised key is dropped in silence — the plan would then
# describe a column that does not exist. Same purpose as :data:`ALIASES` for hyperparameters.
PREPROCESSING_ALIASES: dict[str, str] = {
    "add_missing_indicators": MISSING_INDICATOR,
    "add_missing_indicator": MISSING_INDICATOR,
    "missing_indicators": MISSING_INDICATOR,
    "add_indicator": MISSING_INDICATOR,
    "missing_counts": MISSING_COUNT,
    "n_missing": MISSING_COUNT,
}


def _wrap_preprocessing(
    key: str, model: Any, preprocessing: dict[str, Any], log: LogBuffer
) -> Any:
    """Build the pipeline the *config* describes, not a fixed one.

    The config used to be written into the artifacts and then ignored here, so a report
    could state "mean imputation" about a run that imputed medians. Absent keys keep the
    old defaults — median, and scaling only where the estimator needs it — so a config
    that says nothing behaves exactly as before.

    ``impute: none`` drops the imputer, and that is the one setting whose validity depends
    on ``key``: only :data:`NATIVE_NAN` families survive a NaN at ``fit``. Asking for it
    anywhere else is downgraded to the default rather than failing the attempt, because a
    plan that guesses wrong about a family should cost a log line, not an iteration. The
    downgrade is logged for the same reason the applied hyperparameters are recorded — the
    alternative is a report describing preprocessing that did not run.
    """
    from sklearn.impute import SimpleImputer
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import FunctionTransformer, StandardScaler

    preprocessing = {
        PREPROCESSING_ALIASES.get(str(name), str(name)): value
        for name, value in preprocessing.items()
    }
    requested = preprocessing.get("impute")
    strategy = DEFAULT_IMPUTE if requested is None else str(requested)
    if strategy == IMPUTE_NONE and key not in NATIVE_NAN:
        log.write(
            f"impute={IMPUTE_NONE} needs a family that splits on NaN "
            f"({', '.join(sorted(NATIVE_NAN))}); {key} does not, using {DEFAULT_IMPUTE}"
        )
        strategy = DEFAULT_IMPUTE
    elif strategy not in (*IMPUTE_STRATEGIES, IMPUTE_NONE):
        log.write(f"unknown impute strategy {requested!r}; using {DEFAULT_IMPUTE}")
        strategy = DEFAULT_IMPUTE

    # An explicit ``scale`` decides; otherwise the estimator does, as before.
    scale = preprocessing.get("scale")
    should_scale = bool(scale) if isinstance(scale, bool) else key in SCALE_SENSITIVE

    steps: list[tuple[str, Any]] = []
    # Before the imputer, in this order. The count runs after the indicator so it counts the
    # original columns only — the appended indicators hold no NaN, so the total is unchanged
    # either way, but the order makes that independence explicit rather than incidental.
    indicate = bool(preprocessing.get(MISSING_INDICATOR))
    count = bool(preprocessing.get(MISSING_COUNT))
    if indicate:
        steps.append((MISSING_INDICATOR, FunctionTransformer(append_missing_indicator)))
    if count:
        steps.append((MISSING_COUNT, FunctionTransformer(append_missing_count)))
    if strategy != IMPUTE_NONE:
        steps.append(("impute", SimpleImputer(strategy=strategy)))
    if should_scale:
        steps.append(("scale", StandardScaler()))
    steps.append(("model", model))
    log.write(
        f"preprocessing applied: impute={strategy} scale={should_scale} "
        f"{MISSING_INDICATOR}={indicate} {MISSING_COUNT}={count}"
    )
    return Pipeline(steps)


def describe_preprocessing(estimator: Any) -> dict[str, Any]:
    """What the pipeline *is*, read off the object rather than recomputed.

    :func:`_wrap_preprocessing` silently downgrades a request it cannot honour — an
    ``impute: none`` outside :data:`NATIVE_NAN` becomes a median, an unknown strategy
    becomes the default — so the config is not a record of what ran. Deriving the answer
    from the config a second time here would be a second code path free to disagree with
    the first; inspecting the built pipeline cannot.

    This exists for the same reason ``applied_hyperparams`` does. Without it a report had
    only the card's ``preprocessing`` block to quote, which is the *card's* default and not
    the plan's override, and one run's write-up duly announced median imputation with
    scaling for an attempt that had run neither.
    """
    steps = getattr(estimator, "named_steps", None)
    if not steps:
        return {}
    imputer = steps.get("impute")
    return {
        "impute": IMPUTE_NONE if imputer is None else str(getattr(imputer, "strategy", "")),
        "scale": "scale" in steps,
        # Reported whether on or off, like ``scale``: a write-up that has to distinguish
        # "no indicators" from "this run predates the field" needs the false, not a gap.
        MISSING_INDICATOR: MISSING_INDICATOR in steps,
        MISSING_COUNT: MISSING_COUNT in steps,
    }


