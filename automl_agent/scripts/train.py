def scorers(
    y_true: Any, pred: Any, proba: Any, average: str, task: str = TASK_CLASSIFICATION
) -> dict[str, Any]:
    """Thunk per registry metric, so nothing is computed unless it is asked for.

    Also called by ``scripts/profile.py`` — a duplicate of these two branches used to live
    there, and the bar and the scores it is compared against have to be the *same*
    measurement: ``rmse`` differing by a square root between the two files would be a
    comparison nobody could see was wrong. One definition is what makes that drift impossible.

    The regression side is deliberately the *unscaled* metrics: ``mae`` and ``rmse`` come
    back in the target column's own units, which is what makes them readable to someone who
    knows the data — and what makes a portable default bar impossible
    (:func:`automl_agent.scoring.goal.default_bar`).

    sklearn is imported inside the branches so importing this module stays free of it, which
    is what lets the profiler call it without either script paying for the other's estimators.
    """
    if task == TASK_REGRESSION:
        from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

        return {
            "r2": lambda: r2_score(y_true, pred),
            "mae": lambda: mean_absolute_error(y_true, pred),
            # Not ``squared=False``: removed in sklearn 1.6, and
            # ``root_mean_squared_error`` does not exist before 1.4.
            "rmse": lambda: float(mean_squared_error(y_true, pred)) ** 0.5,
        }

    from sklearn.metrics import (
        accuracy_score,
        average_precision_score,
        balanced_accuracy_score,
        f1_score,
        precision_score,
        recall_score,
        roc_auc_score,
    )

    return {
        "f1": lambda: f1_score(y_true, pred, average=average, zero_division=0),
        "accuracy": lambda: accuracy_score(y_true, pred),
        "balanced_accuracy": lambda: balanced_accuracy_score(y_true, pred),
        "precision": lambda: precision_score(y_true, pred, average=average, zero_division=0),
        "recall": lambda: recall_score(y_true, pred, average=average, zero_division=0),
        "roc_auc": lambda: roc_auc_score(y_true, proba),
        "pr_auc": lambda: average_precision_score(y_true, proba),
    }


def score_split(
    names: list[str],
    y_true: Any,
    pred: Any,
    proba: Any,
    average: str,
    log: LogBuffer,
    task: str = TASK_CLASSIFICATION,
) -> dict[str, float]:
    """Score ``names`` on one split, skipping what this prediction cannot support.

    Registry-driven on purpose. Every metric ``--metric`` accepts *for this task* is emitted
    here, so a goal derived for one of them is measured against a number that exists — a
    metric the goal knew about but the result lacked used to read as "never reached the bar".
    """
    thunks = scorers(y_true, pred, proba, average, task)
    scores: dict[str, float] = {}
    for name in names:
        spec = METRICS.get(name)
        if spec is None:  # pragma: no cover - guarded by RunConfig validation
            continue
        if spec.task != task:
            # Not a skip worth logging: the other task's metrics are not missing from this
            # result, they are not defined for it.
            continue
        if spec.binary_only and average != "binary":
            log.write(f"{name} skipped: defined for binary targets only (average={average})")
            continue
        if spec.needs_proba and proba is None:
            continue
        try:
            value = float(thunks[name]())
        except (ValueError, AttributeError) as exc:
            log.write(f"{name} skipped: {exc}")
            continue
        if not math.isfinite(value):
            # sklearn returns NaN instead of raising for some inputs it cannot score —
            # ``roc_auc`` with one class in ``y_true`` is the reachable one. NaN is not a
            # score and it is worse than an absent key: ``json.dumps`` writes it as bare
            # ``NaN``, which is not valid JSON for a strict reader; every comparison against
            # it is False, so a goal check reads "did not reach the bar"; and a prompt or a
            # batch summary prints it as though a measurement had been made.
            log.write(f"{name} skipped: not defined on these rows (returned {value})")
            continue
        scores[name] = value
    return scores


def specificity(y_true: Any, pred: Any) -> float:
    """True-negative rate — recall with the negative class as the positive one.

    Binary only, and deliberately *not* a registry metric: nobody may target it, because a
    model that predicts the majority class for everything scores 1.0. It is emitted for the
    same reason ``train_val_gap`` is — as a diagnostic. ``balanced_accuracy`` is
    ``(recall + specificity) / 2``, so these two numbers are the only thing that names
    which way the imbalance lever has to move, and without them the Critic guesses.
    """
    from sklearn.metrics import recall_score

    return float(recall_score(y_true, pred, pos_label=0, zero_division=0))


def bootstrap_resamples(cfg: dict[str, Any]) -> int:
    """How many resamples the confidence interval gets. ``0`` turns it off.

    Read from the config rather than fixed so a caller with a 500,000-row split has an
    escape hatch, but with no CLI flag: the interval is the difference between "개선됨" and
    "이 행들로는 구분되지 않음", and a knob invites turning it off to make a run look
    decisive. Junk values fall back to the default instead of failing the run.
    """
    raw = dict(cfg.get("bootstrap") or {}).get("resamples", DEFAULT_RESAMPLES)
    if isinstance(raw, bool) or not isinstance(raw, (int, float)):
        return DEFAULT_RESAMPLES
    return max(0, int(raw))


def _proba(model: Any, x_arr: Any, n_classes: int, log: LogBuffer) -> Any:
    """Positive-class probabilities, or None when this model/target cannot give them."""
    if n_classes != 2 or not hasattr(model, "predict_proba"):
        return None
    try:
        return model.predict_proba(x_arr)[:, 1]
    except (ValueError, AttributeError, IndexError) as exc:
        log.write(f"predict_proba unavailable: {exc}")
        return None


