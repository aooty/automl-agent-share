"""Fixed training script. Run as an isolated subprocess by ``nodes/training.py``.

This file is *not* generated by an LLM. It is verified code whose behaviour is
driven entirely by the injected config: model name, hyperparameters and data
source. That keeps the execution path deterministic and auditable.

Contract
--------
Input  : ``--config <path>`` (JSON), ``--out <path>`` (where to write result.json),
         optionally ``--score-model <model.joblib>``
Output : ``result.json``::

    {"metrics": {...}, "split": "val" | "test", "applied_hyperparams": {...},
     "dropped_hyperparams": [...], "train_time_sec": float,
     "status": "ok" | "error", "error_type": str | null, "log_tail": str,
     "model_path": str | null}

plus ``model.joblib`` beside it — the fitted pipeline, so the best attempt can be scored
again later without refitting. ``model_path`` is local: it is not in
``privacy.PUBLIC_RESULT_FIELDS``, because a fitted estimator is data-equivalent (an SVC
stores support vectors verbatim).

Two modes, one file. Without ``--score-model`` it fits on the training split and reports
*validation* scores. With it, nothing is fitted: the saved model is scored once on the
test split that :mod:`automl_agent.scoring.splits` held back from the whole run, which is the only
number in the report that no decision was selected against.

Fields whose *why* lives at the code that writes them, named here only so the shape of
``result.json`` is readable in one place:

``applied_hyperparams``  what the estimator was really configured with, after the proposal was
                         narrowed to what this model accepts. The report quotes this, not the
                         proposal.
``internal_validation``  training rows kept out of the fit, by the estimator itself or by the
                         harness (:func:`describe_internal_validation`, :func:`fit_estimator`)
                         or by the decision cut. Its ``fit_rows`` is what the attempt was
                         fitted on; absent when nothing was held back.
``metrics``              every registry metric of the target's task the prediction supports,
                         each one's ``train_`` counterpart, ``train_val_gap`` on the goal
                         metric, and on a binary target ``specificity``,
                         ``balanced_accuracy_at_best_cut`` and
                         ``balanced_accuracy_cut_headroom``. Those four are diagnostics — nothing
                         may target them (:mod:`automl_agent.capabilities`).
``*_ci_low`` / ``_high`` 95% bootstrap interval on the goal metric over the split just scored,
                         resampled by group when the split was grouped. Two floats because
                         ``privacy.public_result`` keeps only numeric metric values; see
                         :mod:`automl_agent.scoring.intervals` for what the width means.

Exit code is 0 even for training failures (OOM included) so the orchestrator can
treat them as normal flow and hand them to the Critic. The only non-zero exit is
the deliberately simulated hard crash, which exists to prove the orchestrator
survives a dying subprocess.

Config shape
------------
    {
      "model": "hist_gbdt",
      "hyperparams": {"max_iter": 200, "learning_rate": 0.1},
      "preprocessing": {"impute": "median", "scale": true},
      "target_missing": {"policy": "reject" | "drop"},
      "data": {"path": null, "target_column": "target",
               "synthetic": {"n_samples": 5000, "n_features": 20, ...}},
      "metric": "f1",
      "seed": 42,
      "memory_limit_mb": 512,
      "bootstrap": {"resamples": 400},
      "paired_baseline": {"iteration": 3, "path": ".../iter_03/val_predictions.npz"},
      "simulate": {"fail": "oom" | "crash", "sleep_sec": 0}
    }
"""

