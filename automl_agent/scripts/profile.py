def _mirror_aliases(scores: dict[str, float]) -> dict[str, float]:
    """Publish each score under its alias too, so either spelling reads the card."""
    for alias, target in ALIASES.items():
        if target in scores:
            scores[alias] = scores[target]
    return scores


def _score_all(
    y_true: Any, pred: Any, proba: Any, average: str, task: str = TASK_CLASSIFICATION
) -> dict[str, float]:
    """Score every registry metric this prediction can support.

    Driven by the registry rather than a hand-kept list: the baseline then covers exactly
    the metrics ``--metric`` accepts *for this task*, which is the property that makes an
    ``auto`` bar derivable for any of them.
    """
    thunks = scorers(y_true, pred, proba, average, task)
    scores: dict[str, float] = {}
    for name, spec in METRICS.items():
        if spec.task != task:
            continue
        scorer = thunks.get(name)
        if scorer is None:  # pragma: no cover - a registry entry with no scorer here
            continue
        if spec.binary_only and average != "binary":
            continue
        if spec.needs_proba and proba is None:
            continue
        # A single-class holdout has no AUC; the threshold metrics still have values.
        with contextlib.suppress(ValueError):
            scores[name] = round(float(scorer()), 4)
    return _mirror_aliases(scores)


def _baseline_intervals(
    y_true: Any,
    pred: Any,
    proba: Any,
    average: str,
    scores: dict[str, float],
    *,
    task: str = TASK_CLASSIFICATION,
    groups: Any = None,
    seed: int = 42,
    resamples: int = DEFAULT_RESAMPLES,
) -> dict[str, Any] | None:
    """A 95% bootstrap interval for every baseline score, or ``None`` if none is measurable.

    *Every* score, not just one: the card is written before ``--metric`` is chosen, so
    picking a single metric here would half the time be the wrong one. The cost is at most
    seven metrics times ``resamples`` over the validation slice, which is seconds on a
    profiling run that already fits a model.

    This is where the interval pays for itself, because the baseline is the *bar*: an
    ``auto`` threshold is derived from these numbers (:mod:`automl_agent.scoring.goal`), and a bar
    sitting inside the interval of the score it was derived from is a bar within the noise
    floor of this dataset's validation slice. ``goal.describe`` says so before the loop
    starts, which is one iteration budget cheaper than finding out afterwards.
    """
    bounds: dict[str, Any] = {}
    unit, drawn = "row", 0
    for name in METRICS:
        if name not in scores:
            continue

        def one(y_slice: Any, pred_slice: Any, proba_slice: Any, metric: str = name) -> float:
            return float(scorers(y_slice, pred_slice, proba_slice, average, task)[metric]())

        interval = bootstrap_interval(
            one, y_true, pred, proba, groups=groups, seed=seed, resamples=resamples
        )
        if interval is None:
            continue
        # Four decimals, like ``scores`` and ``chance``: the card's numbers are read side by
        # side, and a bound printed to six would claim a precision 400 resamples do not have.
        bounds[name] = {"low": round(interval.low, 4), "high": round(interval.high, 4)}
        unit, drawn = interval.unit, interval.resamples
    if not bounds:
        return None
    # Mirrored under the aliases, like ``scores`` and ``chance``, so a card read under
    # either spelling finds the same interval.
    for alias, target in ALIASES.items():
        if target in bounds:
            bounds[alias] = bounds[target]
    return {"level": CI_LEVEL, "unit": unit, "resamples": drawn, "scores": bounds}


def reference_scores(
    features: Any,
    codes: Any,
    n_classes: int,
    *,
    task: str = TASK_CLASSIFICATION,
    seed: int = 42,
    groups: Any = None,
    group_column: str | None = None,
    resamples: int = DEFAULT_RESAMPLES,
) -> dict[str, Any] | None:
    """Fit the fixed reference baseline and return its holdout scores.

    Also returns ``chance`` — a predictor that uses no feature at all, on the same split —
    because a baseline score is only interpretable next to it. On an 11%-positive cohort
    ``accuracy 0.89`` is chance, and a threshold derived from it would be a lie. The
    regression counterpart is the *mean* predictor, and it is the more important of the two:
    ``r2`` is defined against it (so chance is 0.0 by construction) and an ``mae`` is
    meaningless until you know what predicting the mean already costs.

    Returns ``None`` rather than raising: the card is the deliverable here, and a
    dataset the baseline cannot handle is exactly the kind the agent should still get
    to attempt.
    """
    import numpy as np
    from sklearn.impute import SimpleImputer
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import StandardScaler

    regression = task == TASK_REGRESSION
    if features.shape[1] == 0 or (not regression and n_classes < 2):
        return None

    x_arr = np.asarray(features.to_numpy(), dtype="float64")
    y_arr = np.asarray(codes, dtype="float64" if regression else None)
    group_arr = np.asarray(groups) if groups is not None else None
    if len(y_arr) > BASELINE_MAX_ROWS:
        x_arr, y_arr = x_arr[:BASELINE_MAX_ROWS], y_arr[:BASELINE_MAX_ROWS]
        if group_arr is not None:
            group_arr = group_arr[:BASELINE_MAX_ROWS]

    try:
        # The same three-way protocol train.py uses, from the same function. The test
        # slice is *ignored* here on purpose: the baseline is a validation-set score, like
        # every attempt's, and the test rows stay unread until the loop is over.
        splits = split_three_way(x_arr, y_arr, seed, groups=group_arr, stratify=not regression)
        x_train, y_train = splits.x_train, splits.y_train
        x_val, y_val = splits.x_val, splits.y_val
        if regression:
            from sklearn.dummy import DummyRegressor
            from sklearn.linear_model import Ridge

            estimator: Any = Ridge(random_state=seed)
            dummy: Any = DummyRegressor(strategy="mean")
        else:
            from sklearn.dummy import DummyClassifier
            from sklearn.linear_model import LogisticRegression

            estimator = LogisticRegression(max_iter=1000, random_state=seed)
            dummy = DummyClassifier(strategy="prior")
        model = Pipeline(
            [
                ("impute", SimpleImputer(strategy="median")),
                ("scale", StandardScaler()),
                ("model", estimator),
            ]
        )
        model.fit(x_train, y_train)
        dummy.fit(x_train, y_train)

        average = "binary" if not regression and n_classes == 2 else "macro"
        proba = (
            model.predict_proba(x_val)[:, 1] if not regression and n_classes == 2 else None
        )
        pred = model.predict(x_val)
        scores = _score_all(y_val, pred, proba, average, task)
        chance = _score_all(y_val, dummy.predict(x_val), None, average, task)
        # A prior-only predictor has no ranking information at all, by definition — so
        # its two ranking metrics are constants rather than something to measure. AUC is
        # 0.5; average precision of a constant ranker is the positive rate, which is why
        # a pr_auc bar has to be read against the class balance and not against 0.5.
        if not regression and n_classes == 2:
            chance["roc_auc"] = 0.5
            chance["pr_auc"] = round(float(np.mean(np.asarray(y_val) == 1)), 4)
            _mirror_aliases(chance)
    except (ValueError, MemoryError, ImportError) as exc:
        print(f"reference baseline skipped: {type(exc).__name__}: {exc}", flush=True)
        return None

    reference: dict[str, Any] = {
        "model": BASELINE_MODELS[task],
        "note": BASELINE_NOTE.format(estimator=BASELINE_ESTIMATORS[task], seed=seed),
        "n_rows_used": int(len(y_arr)),
        # Which rows produced these numbers. Published so the card can be *refused* when a
        # run's protocol disagrees with it, instead of silently comparing a bar derived
        # here against scores measured over different rows — automl_agent.scoring.splits.
        "protocol": protocol(seed, group_column, stratified=not regression),
        # Its neighbour above says which rows produced these numbers; this says which
        # environment did. Both are here for the same reason: in ``auto`` mode these scores
        # *are* the bar the loop is judged against, and a bar measured in one thread state
        # against attempts fitted in another is off by up to 0.0077 balanced_accuracy
        # (:mod:`automl_agent.threads`) — enough to decide whether iteration 1 already cleared
        # it. Costs four lines of the planning prompt, which is what ``protocol`` costs.
        "threads": thread_state(),
        "scores": scores,
        "chance": chance,
    }
    # The ranking's own limit, in policy for the same reason the scores are: a statistic
    # over the whole holdout. It is what tells the goal derivation that a bar is above
    # anything this ranking can reach at *any* cut — see automl_agent.scoring.ranking. There is no
    # ranking to measure without a probability, so a regression baseline has neither field.
    ks = ks_statistic(y_val, proba)
    ceiling = best_cut_ceiling(ks)
    if ks is not None and ceiling is not None:
        reference["ks"] = round(ks, 4)
        reference["balanced_accuracy_at_best_cut"] = ceiling
    # How much of each score above is the validation slice rather than the model. Grouped
    # when the split was grouped, because five visits of one patient are not five
    # observations — automl_agent.scoring.intervals.
    intervals = _baseline_intervals(
        y_val,
        pred,
        proba,
        average,
        scores,
        task=task,
        groups=splits.groups_val,
        seed=seed,
        resamples=resamples,
    )
    if intervals is not None:
        reference["ci"] = intervals
    return reference


