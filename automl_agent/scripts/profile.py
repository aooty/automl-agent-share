# The reference baseline. Fixed so its score means the same thing across runs and
# across datasets: "what a competent default already gets here". One per task, and the
# regression side is Ridge for the same reason the classification side is LogisticRegression:
# a regularised linear model is the cheapest thing that is not a straw man, so beating it
# means something and failing to beat it is a finding.
